#!/usr/bin/env node
import { getContext } from '@keystone-6/core/context'
import type { KeystoneContext } from '@keystone-6/core/types'
import * as PrismaModule from '@prisma/client'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import config from '../index'

function viewName(path: string) {
  if (path === '@keystone-6/core/___internal-do-not-use-will-break-in-patch/admin-ui/id-field-view') return 'id'
  const builtIn = path.match(/^@keystone-6\/core\/fields\/types\/([^/]+)\/views$/)
  if (builtIn) return builtIn[1]
  if (path === '@keystone-6/fields-document/views') return 'document'
  throw new Error(`Unsupported field view: ${path}`)
}

/** Core6.5.3 exposes initialized fields through Context.__internal. Match its
 * create-admin-meta iteration, including omitted lists/relations/custom views,
 * instead of copying an obsolete Keystone initializer with ts-nocheck.
 * This pinned internal shape is checked by native model-route QA and tests.
 */
export function fieldViewOrder(context: Pick<KeystoneContext, '__internal'>) {
  const lists = context.__internal.lists
  const omitted = new Set(Object.entries(lists).filter(([, list]) => !list.graphql.isEnabled.query).map(([key]) => key))
  const paths = new Set<string>()
  for (const [key, list] of Object.entries(lists)) {
    if (omitted.has(key)) continue
    for (const field of Object.values(list.fields)) {
      if (field.dbField.kind === 'relation' && omitted.has(field.dbField.list)) continue
      if (Object.values(field.graphql.isEnabled).every(value => value === false)) continue
      paths.add(field.views)
      if (field.ui.views !== null) paths.add(field.ui.views)
    }
  }
  return [...paths].map(viewName)
}
/** Keystone's views index 0 is the id field view; the dashboard supplies that slot. */
export function dashboardViewOrder(order: string[]) {
  if (order[0] !== 'id') throw new Error('Expected the id field view first in the Keystone view order.')
  return order.slice(1)
}

export async function main() {
  const context = getContext(config, PrismaModule)
  try {
    // The dashboard's getFieldTypeFromViewsIndex prepends 'id' itself, so the
    // emitted order starts after Keystone's id-field view (always index 0).
    const views = dashboardViewOrder(fieldViewOrder(context))
    const output = `/**
 * Auto-generated view order configuration from Keystone models
 * This file is generated by view-order/generate-view-order.ts
 * DO NOT EDIT THIS FILE MANUALLY
 */
export const VIEW_ORDER = ${JSON.stringify(views, null, 2)};\n`
    writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'index.ts'), output)
    console.log(`Generated view order with ${views.length} field types: ${views.join(', ')}`)
  } finally { await context.prisma.$disconnect() }
}
if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) main().catch(() => { console.error('Field view generation failed.'); process.exitCode = 1 })
